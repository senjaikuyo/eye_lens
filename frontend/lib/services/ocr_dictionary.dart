    for (final suf in const ['lah', 'kah', 'pun', 'ku', 'mu', 'nya']) {
      if (current.endsWith(suf) && current.length > suf.length + 2) {
        current = current.substring(0, current.length - suf.length);
        res.add(current);
        break;
      }
    }

    final int len = res.length;
    for (int i = 0; i < len; i++) {
      final base = res[i];
      for (final suf in const ['kan', 'an', 'i']) {
        if (base.endsWith(suf) && base.length > suf.length + 2) {
          res.add(base.substring(0, base.length - suf.length));
        }
      }
    }

    return res;
  }

